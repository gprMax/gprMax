"""Axis and direction identifiers shared by serial and distributed grids."""

from enum import IntEnum, unique


@unique
class Dim(IntEnum):
    X = 0
    Y = 1
    Z = 2


@unique
class Dir(IntEnum):
    NONE = -1
    NEG = 0
    POS = 1
