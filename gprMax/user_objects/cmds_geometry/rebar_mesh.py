"""Orthogonal two-layer reinforcement meshes for concrete models."""

import logging
import math
from dataclasses import dataclass

import gprMax.config as config
from gprMax.cython.geometry_primitives import build_cylinder
from gprMax.grid.fdtd_grid import FDTDGrid
from gprMax.materials import create_directional_material
from gprMax.user_objects.user_objects import GeometryUserObject

from .cmds_geometry import (
    check_averaging,
    geometry_tag_args,
    resolve_geometry_materials,
    validate_geometry_rasterisation,
)

logger = logging.getLogger(__name__)

_TOLERANCE = 1e-12
_POSITION_TOLERANCE = 1e-9


@dataclass(frozen=True)
class RebarSegment:
    """A single circular bar generated by :class:`RebarMesh`.

    Attributes:
        p1: Coordinates of the first bar end.
        p2: Coordinates of the second bar end.
        diameter: Bar diameter in metres.
        layer: ``"top"`` or ``"bottom"``.
    """

    p1: tuple[float, float, float]
    p2: tuple[float, float, float]
    diameter: float
    layer: str

    @property
    def radius(self) -> float:
        """Bar radius in metres."""

        return 0.5 * self.diameter

    @property
    def length(self) -> float:
        """Centre-line length in metres."""

        return math.dist(self.p1, self.p2)

    @property
    def axis(self) -> str:
        """Cartesian axis parallel to the bar."""

        deltas = [abs(self.p2[index] - self.p1[index]) for index in range(3)]
        return "xyz"[deltas.index(max(deltas))]


class RebarMesh(GeometryUserObject):
    """Creates a two-layer orthogonal reinforcement mesh in a rectangular slab.

    The mesh occupies the box defined by ``p1`` and ``p2``. The upper layer
    runs along x, the lower layer runs along y, and both layers use circular
    cylinders. A zero ``layer_spacing`` places both layers at the same height.

    Attributes:
        p1: One corner of the reinforced volume.
        p2: The opposite corner of the reinforced volume.
        spacing: Scalar or ``(x, y)`` centre-to-centre bar spacing in metres.
        diameter: Bar diameter in metres.
        cover: Clear cover from the top and side faces in metres.
        layer_spacing: Vertical centre-to-centre distance between layers.
        material_id: Material identifier used by every bar.
        material_ids: Three identifiers for the x, y, and z material axes.
        averaging: Optional ``y``/``n`` dielectric-smoothing override.
        tag: Optional semantic geometry tag.
    """

    @property
    def hash(self):
        return "#rebar_mesh"

    _allowed_kwargs = frozenset({
        "averaging",
        "cover",
        "diameter",
        "layer_spacing",
        "material_id",
        "material_ids",
        "p1",
        "p2",
        "spacing",
        "tag",
    })

    def __init__(self, **kwargs):
        super().__init__(**kwargs)
        self._bars = self._layout_bars()

    @property
    def bars(self) -> tuple[RebarSegment, ...]:
        """Bars generated by the mesh layout."""

        return self._bars

    @property
    def bar_count(self) -> int:
        """Total number of bars in both layers."""

        return len(self._bars)

    @property
    def total_length(self) -> float:
        """Sum of all bar centre-line lengths in metres."""

        return math.fsum(bar.length for bar in self._bars)

    def _layout_bars(self) -> tuple[RebarSegment, ...]:
        p1 = self._point(self.kwargs.get("p1"), "p1")
        p2 = self._point(self.kwargs.get("p2"), "p2")
        spacing = self._spacing(self.kwargs.get("spacing"))
        diameter = self._positive(self.kwargs.get("diameter"), "diameter")
        cover = self._non_negative(self.kwargs.get("cover"), "cover")
        layer_spacing = self._non_negative(
            self.kwargs.get("layer_spacing", 0.0), "layer_spacing"
        )

        if spacing[0] < diameter - _TOLERANCE or spacing[1] < diameter - _TOLERANCE:
            raise ValueError(
                f"{self.params_str()} bar spacing must be at least one bar diameter"
            )
        if _TOLERANCE < layer_spacing < diameter - _TOLERANCE:
            raise ValueError(
                f"{self.params_str()} layer_spacing must be zero or at least one "
                "bar diameter"
            )

        self._validate_materials()
        lower = tuple(min(p1[index], p2[index]) for index in range(3))
        upper = tuple(max(p1[index], p2[index]) for index in range(3))
        radius = 0.5 * diameter

        self._require_span(lower, upper, cover, radius, layer_spacing)

        top_z = upper[2] - cover - radius
        bottom_z = top_z - layer_spacing
        x_start = lower[0] + cover + radius
        x_stop = upper[0] - cover - radius
        y_start = lower[1] + cover + radius
        y_stop = upper[1] - cover - radius

        x_centres = self._positions(x_start, x_stop, spacing[0])
        y_centres = self._positions(y_start, y_stop, spacing[1])

        bars = []
        for y in y_centres:
            bars.append(
                RebarSegment(
                    p1=(lower[0] + cover, y, top_z),
                    p2=(upper[0] - cover, y, top_z),
                    diameter=diameter,
                    layer="top",
                )
            )
        for x in x_centres:
            bars.append(
                RebarSegment(
                    p1=(x, lower[1] + cover, bottom_z),
                    p2=(x, upper[1] - cover, bottom_z),
                    diameter=diameter,
                    layer="bottom",
                )
            )

        return tuple(bars)

    def _validate_materials(self) -> None:
        material_id = self.kwargs.get("material_id")
        material_ids = self.kwargs.get("material_ids")

        if material_id is not None and material_ids is not None:
            raise ValueError(
                f"{self.params_str()} specify either material_id or material_ids, "
                "not both"
            )
        if material_id is not None:
            if not isinstance(material_id, str) or not material_id.strip():
                raise ValueError(f"{self.params_str()} material_id must be a non-empty string")
            return
        if material_ids is not None:
            if isinstance(material_ids, str):
                raise ValueError(
                    f"{self.params_str()} material_ids requires three identifiers"
                )
            try:
                count = len(material_ids)
            except TypeError as error:
                raise ValueError(
                    f"{self.params_str()} material_ids requires three identifiers"
                ) from error
            if count != 3:
                raise ValueError(
                    f"{self.params_str()} material_ids requires three identifiers"
                )
            if any(
                not isinstance(value, str) or not value.strip()
                for value in material_ids
            ):
                raise ValueError(
                    f"{self.params_str()} material_ids must contain non-empty strings"
                )
            return
        raise ValueError(f"{self.params_str()} no materials have been specified")

    @staticmethod
    def _point(value, name: str) -> tuple[float, float, float]:
        if isinstance(value, (str, bytes)) or value is None:
            raise ValueError(f"{name} must contain three finite coordinates")
        try:
            coordinates = tuple(value)
        except TypeError as error:
            raise ValueError(
                f"{name} must contain three finite coordinates"
            ) from error
        if len(coordinates) != 3:
            raise ValueError(f"{name} must contain three finite coordinates")
        try:
            point = tuple(float(coordinate) for coordinate in coordinates)
        except (TypeError, ValueError) as error:
            raise ValueError(
                f"{name} must contain three finite coordinates"
            ) from error
        if any(not math.isfinite(coordinate) for coordinate in point):
            raise ValueError(f"{name} must contain three finite coordinates")
        return point

    @staticmethod
    def _spacing(value) -> tuple[float, float]:
        if isinstance(value, (str, bytes, bool)) or value is None:
            raise ValueError("spacing must be a positive scalar or an (x, y) pair")
        try:
            values = tuple(value)
        except TypeError:
            values = None

        if values is None:
            try:
                spacing = (float(value), float(value))
            except (TypeError, ValueError) as error:
                raise ValueError(
                    "spacing must be a positive scalar or an (x, y) pair"
                ) from error
        else:
            if len(values) != 2:
                raise ValueError("spacing must be a positive scalar or an (x, y) pair")
            try:
                spacing = (float(values[0]), float(values[1]))
            except (TypeError, ValueError) as error:
                raise ValueError(
                    "spacing must be a positive scalar or an (x, y) pair"
                ) from error

        if any(not math.isfinite(item) or item <= 0 for item in spacing):
            raise ValueError("spacing must be a positive scalar or an (x, y) pair")
        return spacing

    @staticmethod
    def _positive(value, name: str) -> float:
        try:
            number = float(value)
        except (TypeError, ValueError) as error:
            raise ValueError(f"{name} must be a finite positive value") from error
        if isinstance(value, bool) or not math.isfinite(number) or number <= 0:
            raise ValueError(f"{name} must be a finite positive value")
        return number

    @staticmethod
    def _non_negative(value, name: str) -> float:
        try:
            number = float(value)
        except (TypeError, ValueError) as error:
            raise ValueError(f"{name} must be a finite non-negative value") from error
        if isinstance(value, bool) or not math.isfinite(number) or number < 0:
            raise ValueError(f"{name} must be a finite non-negative value")
        return number

    def _require_span(
        self,
        lower: tuple[float, float, float],
        upper: tuple[float, float, float],
        cover: float,
        radius: float,
        layer_spacing: float,
    ) -> None:
        if upper[0] - lower[0] < 2 * cover + 2 * radius - _TOLERANCE:
            raise ValueError(
                f"{self.params_str()} x span is too small for the requested cover "
                "and diameter"
            )
        if upper[1] - lower[1] < 2 * cover + 2 * radius - _TOLERANCE:
            raise ValueError(
                f"{self.params_str()} y span is too small for the requested cover "
                "and diameter"
            )
        if upper[2] - lower[2] < cover + 2 * radius - _TOLERANCE:
            raise ValueError(
                f"{self.params_str()} z span is too small for the requested cover "
                "and diameter"
            )
        bottom_z = upper[2] - cover - radius - layer_spacing
        if bottom_z < lower[2] + radius - _TOLERANCE:
            raise ValueError(
                f"{self.params_str()} layer_spacing places the lower layer outside "
                "the reinforced volume"
            )

    @staticmethod
    def _positions(start: float, stop: float, spacing: float) -> tuple[float, ...]:
        if start > stop + _POSITION_TOLERANCE:
            raise ValueError(
                "the reinforced volume is too small for the requested cover and diameter"
            )
        count = int(math.floor((stop - start) / spacing + _POSITION_TOLERANCE)) + 1
        return tuple(
            min(start + index * spacing, stop) for index in range(count)
        )

    def build(self, grid: FDTDGrid):
        """Rasterise every generated bar into the supplied grid."""

        if config.get_model_config().mode.startswith("2D"):
            raise ValueError(
                f"{self.__str__()} cannot be used in 2D mode because the mesh is "
                "not invariant along a single axis."
            )

        try:
            average_rebar = check_averaging(self.kwargs["averaging"])
        except KeyError:
            average_rebar = grid.averagevolumeobjects

        material_id = self.kwargs.get("material_id")
        material_ids = self.kwargs.get("material_ids")
        if material_id is not None:
            materialsrequested = [material_id]
            directional = False
        else:
            materialsrequested = list(material_ids)
            directional = True

        materials = resolve_geometry_materials(
            grid,
            materialsrequested,
            geometry=self.params_str(),
            directional=directional,
        )

        if len(materials) == 1:
            averaging = materials[0].averagable and average_rebar
            numID = numIDx = numIDy = numIDz = materials[0].numID
            pec_x = pec_y = pec_z = materials[0].is_pec
        else:
            averaging = False
            numIDx = materials[0].numID
            numIDy = materials[1].numID
            numIDz = materials[2].numID
            pec_x = materials[0].is_pec
            pec_y = materials[1].is_pec
            pec_z = materials[2].is_pec
            numID = create_directional_material(grid, materials).numID

        uip = self._create_uip(grid)
        tag_data, tag_id = geometry_tag_args(grid, self.kwargs.get("tag"))
        occupied_total = 0
        for index, bar in enumerate(self._bars, start=1):
            x1, y1, z1 = uip.round_to_grid(bar.p1)
            x2, y2, z2 = uip.round_to_grid(bar.p2)
            occupied = build_cylinder(
                x1,
                y1,
                z1,
                x2,
                y2,
                z2,
                bar.radius,
                grid.dx,
                grid.dy,
                grid.dz,
                numID,
                numIDx,
                numIDy,
                numIDz,
                averaging,
                pec_x,
                pec_y,
                pec_z,
                grid.solid,
                grid.rigidE,
                grid.rigidH,
                grid.ID,
                tag_data,
                tag_id,
            )
            validate_geometry_rasterisation(
                grid,
                occupied,
                geometry=f"{self.params_str()} bar {index} ({bar.layer})",
            )
            occupied_total += occupied

        dielectricsmoothing = "on" if averaging else "off"
        logger.info(
            f"{self.grid_name(grid)}Rebar mesh with {len(self._bars)} bars "
            f"({self.total_length:g}m total) of material(s) "
            f"{', '.join(materialsrequested)} created, dielectric smoothing is "
            f"{dielectricsmoothing}."
        )
        return occupied_total
